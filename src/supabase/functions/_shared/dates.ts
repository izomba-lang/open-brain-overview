// Фаза 20: интервалы считает код, а не модель.
//
// Класс багов, ради которого этот модуль существует, — один и тот же:
// код отдаёт модели величину, которую обязан вычислить сам.
//
//   v1.83.1 — бриф заявил «прошло больше двух недель» про пятидневную
//   просрочку. В промпт уходили две голые даты; вычитание модель сделала в уме
//   и ошиблась. Хуже того, few-shot пример в схеме был сформулирован как
//   «последняя встреча была 16 дней назад» — то есть задавал заодно и порядок
//   величины, которую нечем было проверить.
//
// Правило: любая величина, выводимая из данных (интервал, счётчик, «старше
// чем»), вычисляется здесь и подаётся модели ГОТОВОЙ формулировкой, а промпт
// прямо запрещает выводить новые.
//
// Хелперы жили внутри daily-brief и были недоступны остальным; compile-wiki
// поэтому продолжал просить модель определить, что «старше 30 дней».

// Таймзона владельца: задаётся секретом OWNER_TZ (например "Europe/Berlin").
const DEFAULT_TZ = Deno.env.get("OWNER_TZ") || "UTC";

/**
 * Разница в КАЛЕНДАРНЫХ днях в таймзоне владельца.
 *
 * Не в прошедших часах: дедлайн «вчера» должен читаться как 1 день независимо
 * от того, в котором часу он был поставлен. На границе таймзоны это даёт
 * заметную разницу — заметка от 18.07 21:29 UTC это 19.07 по Иерусалиму.
 */
export function dayDiff(fromISO: string, to: Date, tz: string = DEFAULT_TZ): number {
  const dayKey = (d: Date) => d.toLocaleDateString("en-CA", { timeZone: tz });
  const a = new Date(`${dayKey(new Date(fromISO))}T00:00:00Z`).getTime();
  const b = new Date(`${dayKey(to)}T00:00:00Z`).getTime();
  return Math.round((b - a) / 86_400_000);
}

/** Готовая формулировка про срок. Модель её копирует, а не пересчитывает. */
export function deadlineLabel(dueISO: string, now: Date, tz: string = DEFAULT_TZ): string {
  const d = dayDiff(dueISO, now, tz);
  if (d > 0) return `просрочен на ${d} дн.`;
  if (d === 0) return "срок сегодня";
  return `осталось ${-d} дн.`;
}

/** Готовая формулировка про давность. */
export function agoLabel(createdISO: string, now: Date, tz: string = DEFAULT_TZ): string {
  const d = dayDiff(createdISO, now, tz);
  if (d <= 0) return "сегодня";
  if (d === 1) return "вчера";
  return `${d} дн. назад`;
}

/**
 * Дата отсечки в виде YYYY-MM-DD.
 *
 * Нужна там, где промпт говорит «убери старше N дней»: такая формулировка
 * заставляет модель самой считать возраст каждой записи. Вместо неё в промпт
 * подаётся конкретная граница — сравнение двух дат модель делает надёжно,
 * арифметику над ними нет.
 */
export function cutoffDate(daysAgo: number, now: Date, tz: string = DEFAULT_TZ): string {
  const ms = now.getTime() - daysAgo * 86_400_000;
  return new Date(ms).toLocaleDateString("en-CA", { timeZone: tz });
}
